    @staticmethod
    def _sanitize_code(rel_path: str, code: str) -> str:
        if rel_path.endswith(".py"):
            def fix_open(m):
                args = m.group(1)
                if "encoding" in args or "wb" in args or "rb" in args:
                    return m.group(0)
                if re.search(r'["\']r["\']', args):
                    return f'open({args}, encoding="utf-8")'
                if "," not in args:
                    return f'open({args}, "r", encoding="utf-8")'
                return f'open({args}, encoding="utf-8")'

            code = re.sub(r'\bopen\(([^)]+)\)', fix_open, code)
        return code

    def _write_files_from_response(self, ai_text: str, target_dir: Path, file_manager: FileManager):
        written = []
        p1 = r"(?:FILE|File|file):\s*`?([a-zA-Z0-9_\-\./\\]+\.[a-zA-Z0-9]+)`?\s*```(?:[a-zA-Z0-9_\-]+)?\n(.*?)```"
        p2 = r"(?:###|##|#|\*\*)\s*`?([a-zA-Z0-9_\-\./\\]+\.[a-zA-Z0-9]+)`?\s*\**\s*```(?:[a-zA-Z0-9_\-]+)?\n(.*?)```"
        matches = re.findall(p1, ai_text, re.DOTALL) + re.findall(p2, ai_text, re.DOTALL)
        seen = set()
        for rel_path, code in matches:
            clean_rel = rel_path.strip().strip("`* ").replace("\\", "/")
            # Sanitize: Strip any noise like pythonCopyDownload or CopyDownload
            clean_rel = re.sub(r'(?:python)?CopyDownload.*$', '', clean_rel, flags=re.IGNORECASE)
            valid_match = re.search(r'([a-zA-Z0-9_\-\./]+\.(?:py|html|css|js|ts|json|bat|txt|md|sql))\b', clean_rel)
            if valid_match:
                clean_rel = valid_match.group(1)

            if clean_rel in seen:
                continue
            seen.add(clean_rel)
            clean_code = self._sanitize_code(clean_rel, code.strip())
            dest = target_dir / clean_rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            file_manager.write_file(dest, clean_code)
            written.append(clean_rel)

            # Duplicate index.html to both root and static/ for bulletproof serving
            if clean_rel == "index.html" and "static/index.html" not in seen:
                file_manager.write_file(target_dir / "static" / "index.html", clean_code)
            elif clean_rel == "static/index.html" and "index.html" not in seen:
                file_manager.write_file(target_dir / "index.html", clean_code)
        return written

    def _extract_largest_code_block(self, ai_text: str) -> Optional[str]:
        # Match any code block (```python, ```html, ```js, or bare ```)
        blocks = re.findall(r"```(?:[a-zA-Z0-9_\-]+)?\n(.*?)```", ai_text, re.DOTALL)
        if blocks:
            return max(blocks, key=len).strip()
        # Fallback: if ai_text itself is raw code without fences
        if ("import " in ai_text or "from " in ai_text) and ("app = FastAPI" in ai_text or "app = Flask" in ai_text or "uvicorn" in ai_text):
            return ai_text.strip()
        return None

