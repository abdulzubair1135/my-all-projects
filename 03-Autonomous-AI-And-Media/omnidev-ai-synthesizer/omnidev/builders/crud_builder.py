        console.print("[magenta]🤖 Asking DeepSeek/Gemini to write complete app code...[/magenta]")
        import inspect
        sig = inspect.signature(self.brain.ask)
        ai_response = self.brain.ask(generation_prompt, new_chat=True) if "new_chat" in sig.parameters else self.brain.ask(generation_prompt)

        # 2. Extract and write files directly from DeepSeek's response
        files_written = self._write_files_from_response(ai_response, target_dir, app_file_manager)
        if not files_written:
            # Check all code blocks generated by DeepSeek
            blocks = re.findall(r"```(?:[a-zA-Z0-9_\-]+)?\n(.*?)```", ai_response, re.DOTALL)
            if blocks:
                # Find Python backend and HTML/frontend blocks
                py_blocks = [b for b in blocks if "import " in b or "from " in b or "FastAPI" in b or "app =" in b or "def " in b]
                html_blocks = [b for b in blocks if "<!DOCTYPE" in b or "<html" in b]
                
                if py_blocks:
                    main_code = max(py_blocks, key=len).strip()
                    main_code = self._sanitize_code("main.py", main_code)
                    app_file_manager.write_file("main.py", main_code)
