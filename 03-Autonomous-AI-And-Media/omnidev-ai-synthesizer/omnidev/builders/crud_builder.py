class CRUDAppBuilder:
    """
    Builds, launches, tests, and auto-corrects full-stack CRUD applications
    with FastAPI, SQLite, and responsive modern web frontend.
    """
    def __init__(self, brain, workspace_dir: Path, process_manager: Optional[ProcessManager] = None):
        self.brain = brain
        self.workspace_dir = Path(workspace_dir)
        self.file_manager = FileManager(self.workspace_dir)
        self.process_manager = process_manager if process_manager is not None else ProcessManager()
        self.auto_healer = AutoHealer(self.brain, self.file_manager)

    def build_and_launch(self, prompt: str, app_dir_name: str = "generated_app") -> Dict[str, Any]:
        """
        End-to-end flow:
        1. Design models & API endpoints via AI Brain
        2. Generate code files (main.py, models, frontend HTML)
        3. Allocate free port & start server
        4. Run automated CRUD integration test
        5. Auto-heal any runtime errors
        6. Return live URL and test results
        """
        # Derive a dedicated clean folder name for this specific app
        clean_words = [w for w in re.sub(r'[^a-zA-Z0-9\s]', '', prompt.lower()).split() 
                       if w not in ["make", "build", "create", "a", "an", "the", "app", "application", "with", "using", "full", "stack", "fullstack"]]
        app_slug = "_".join(clean_words[:3]) if clean_words else "new_app"
        app_folder = app_dir_name if app_dir_name != "generated_app" else f"apps/{app_slug}"
        target_dir = self.workspace_dir / app_folder
        target_dir.mkdir(parents=True, exist_ok=True)
        app_file_manager = FileManager(target_dir)

        console.print(f"[bold cyan]🚀 Designing Custom Application in:[/bold cyan] '{app_folder}' for: '{prompt}'")

