import express from "express";

import Controller from "../controllers/User.js";

const router = express.Router();


// ============================================================
// GET ALL
//
// GET /users
// ============================================================

router.get(

    "/",

    Controller.getAll

);


// ============================================================
// GET BY ID
//
// GET /users/:id
// ============================================================

router.get(

    "/:id",

    Controller.getById

);


// ============================================================
// CREATE
//
// POST /users
// ============================================================

router.post(

    "/",

    Controller.create

);


// ============================================================
// UPDATE
//
// PUT /users/:id
// ============================================================

router.put(

    "/:id",

    Controller.update

);


// ============================================================
// DELETE
//
// DELETE /users/:id
// ============================================================

router.delete(

    "/:id",

    Controller.delete

);

export default router;